#!/usr/bin/env python3
"""
P4OS - Emulador, Atari 2600 core: turns Stella's DefProps.hxx into
stella/emucore/DefPropsP4.hxx.

Stella's game database is a table of 3250 x 21 string pointers. In a
shared object every one of those pointers is a run-time relocation (about
68,000 of them, 12 bytes each in the .so and work for the loader at every
start), and most of the strings are names, makers and notes the emulator
never reads. This keeps the properties the emulation uses, packs each
entry's values into one string, shares identical ones, and indexes the
whole by the binary MD5: no pointers at all.

    python3 gen_defprops.py <Stella's DefProps.hxx> <out DefPropsP4.hxx>
"""
import re
import sys

# Stella's PropertyType order (Props.hxx); the ones kept, by index.
NAMES = ["Cartridge_MD5", "Cartridge_Manufacturer", "Cartridge_ModelNo",
         "Cartridge_Name", "Cartridge_Note", "Cartridge_Rarity",
         "Cartridge_Sound", "Cartridge_Type", "Console_LeftDifficulty",
         "Console_RightDifficulty", "Console_TelevisionType",
         "Console_SwapPorts", "Controller_Left", "Controller_Right",
         "Controller_SwapPaddles", "Controller_MouseAxis", "Display_Format",
         "Display_YStart", "Display_Height", "Display_Phosphor",
         "Display_PPBlend"]
KEEP = list(range(6, 21))

def c_escape(s):
    out = []
    for ch in s.encode("latin-1"):
        c = chr(ch)
        if c in '"\\':
            out.append("\\" + c)
        elif 32 <= ch < 127:
            out.append(c)
        else:
            out.append("\\%03o" % ch)
    return "".join(out)

def main():
    src = open(sys.argv[1], encoding="latin-1").read()
    rows = []
    for m in re.finditer(r'^\s*\{\s*(".*?")\s*\},?\s*$', src, re.M):
        vals = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))
        if len(vals) != 21:
            raise SystemExit("bad row: %s" % m.group(0)[:80])
        rows.append([v.replace('\\"', '"').replace("\\\\", "\\") for v in vals])
    rows.sort(key=lambda r: r[0].lower())
    blob = bytearray()
    seen = {}
    offs = []
    for r in rows:
        rec = "\x1f".join(r[i] for i in KEEP) + "\x00"
        if rec not in seen:
            seen[rec] = len(blob)
            blob += rec.encode("latin-1")
        offs.append(seen[rec])
    with open(sys.argv[2], "w") as f:
        f.write("/* Generated by cores/a2600/tools/gen_defprops.py from Stella's\n"
                " * DefProps.hxx: do not edit. %d games, %d distinct records.\n"
                " * Each record holds, separated by 0x1f: %s. */\n"
                % (len(rows), len(seen), ", ".join(NAMES[i] for i in KEEP)))
        f.write("#define DEF_PROPS_SIZE %d\n" % len(rows))
        f.write("#define DEF_PROPS_FIRST %d\n" % KEEP[0])
        f.write("#define DEF_PROPS_COUNT %d\n\n" % len(KEEP))
        f.write("static const unsigned char DefPropsMD5[DEF_PROPS_SIZE][16] = {\n")
        for r in rows:
            b = bytes.fromhex(r[0])
            f.write("  {" + ",".join("0x%02x" % x for x in b) + "},\n")
        f.write("};\n\n")
        f.write("static const unsigned short DefPropsRec[DEF_PROPS_SIZE] = {\n")
        for i in range(0, len(offs), 16):
            f.write("  " + ",".join(str(o) for o in offs[i:i + 16]) + ",\n")
        f.write("};\n\n")
        if len(blob) > 65535:
            raise SystemExit("records too large for 16-bit offsets")
        f.write("static const char DefPropsData[] =\n")
        recs = blob.decode("latin-1").split("\x00")[:-1]
        for rec in recs:
            f.write('  "%s\\0"\n' % c_escape(rec).replace("\x1f", "\\037"))
        f.write("  ;\n")

main()
