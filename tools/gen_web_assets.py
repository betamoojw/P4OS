#!/usr/bin/env python3
"""
The portal's page into C: every file gzipped (the browser unpacks it, the
firmware carries a third of the bytes) as an array, plus a table the server
looks paths up in.

    tools/gen_web_assets.py out.c web/index.html web/app.js web/app.css

Both builds run it (components/aos_portal/CMakeLists.txt and sim/CMakeLists.txt),
so the page is always the one in the source tree. The gzip header's date is
fixed so the output only changes when a file does.
"""
from collections import defaultdict
import gzip
import sys
from pathlib import Path

CTYPES = {".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8",
          ".css": "text/css; charset=utf-8", ".svg": "image/svg+xml", ".png": "image/png",
          ".ico": "image/x-icon", ".json": "application/json"}


def language_assets(lang_root):
    """One key table per page. An empty value row means the language falls back."""
    pages = defaultdict(dict)
    for path in sorted(lang_root.glob('*/*.lang')):
        if path.name != '_portal.lang' and not path.name.startswith('web.'):
            continue
        entries = {}
        for line in path.read_bytes().split(b'\n'):
            key, _, value = line.removesuffix(b'\r').partition(b'\t')
            if key and not key.startswith(b'#') and value:
                entries[key] = value
        pages[path.name][path.parent.name] = entries
    for page, locales in sorted(pages.items()):
        keys = sorted(set().union(*locales.values()))
        yield '/builtin-lang/keys/' + page, b'\n'.join(keys)
        for code, entries in locales.items():
            yield f'/builtin-lang/values/{code}/{page}', b'\n'.join(entries.get(k, b'') for k in keys)


def main():
    out = Path(sys.argv[1])
    assets = [('/' + path.name, path.read_bytes()) for path in map(Path, sys.argv[2:])]
    assets.extend(language_assets(Path(__file__).resolve().parents[1] / 'lang'))
    lines = ["/* Generated by tools/gen_web_assets.py from components/aos_portal/web. Do not edit. */",
             "#include <stdint.h>", "",
             "typedef struct { const char *path, *ctype; const uint8_t *data; uint32_t len; } aos_web_asset_t;", ""]
    table = []
    for i, (name, raw) in enumerate(assets):
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        ctype = "text/plain; charset=utf-8" if name.startswith('/builtin-lang/') else CTYPES.get(Path(name).suffix, "application/octet-stream")
        body = ",".join(str(b) for b in gz)
        lines.append("static const uint8_t a%d[%d] = {%s};" % (i, len(gz), body))
        table.append('    { "%s", "%s", a%d, %d },' % (name, ctype, i, len(gz)))
    lines += ["", "const aos_web_asset_t aos_web_assets[] = {"] + table + ["};",
              "const int aos_web_asset_count = %d;" % len(assets), ""]
    text = "\n".join(lines)
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
