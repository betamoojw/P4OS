#!/usr/bin/env bash
#
# Writes apps/python/main/upy/: MicroPython as its embed port turns it into
# plain sources for another program, with this app's configuration
# (main/mpconfigport.h) and the extmod modules it enables.
#
#   apps/python/tools/gen_upy.sh
#
# MicroPython (MIT) is downloaded once into $PY_WORK (default
# ~/.cache/p4os-python) and checked against the hash below. What comes out
# is committed, like Lua's tree: the CI builds python.so without Python
# tools or a download. Run this again after changing mpconfigport.h, the
# module list below, or a module of the app's own that brings new names
# (MP_QSTR_...): the qstr table and the module list are generated here.
set -euo pipefail

HERE=$(cd "$(dirname "$0")/.." && pwd)
WORK=${PY_WORK:-$HOME/.cache/p4os-python}
VER=1.29.0
URL=https://github.com/micropython/micropython/archive/refs/tags/v$VER.tar.gz
SHA=8072f6ad42c0e3bbfca88ed09bf8f1106ce207a39129af920f70081b8f2fe286

for c in curl tar make python3 cc; do command -v $c >/dev/null || { echo "missing on this machine: $c"; exit 1; }; done

mkdir -p "$WORK/dl" "$WORK/src"
F=$WORK/dl/micropython-$VER.tar.gz
if [ ! -f "$F" ]; then echo "downloading MicroPython $VER"; curl -sSL -o "$F.part" "$URL"; mv "$F.part" "$F"; fi
if command -v sha256sum >/dev/null; then sum=$(sha256sum "$F"); else sum=$(shasum -a 256 "$F"); fi
[ "${sum%% *}" = "$SHA" ] || { echo "micropython-$VER.tar.gz: wrong checksum"; exit 1; }
SRC=$WORK/src/micropython-$VER
[ -d "$SRC" ] || tar xzf "$F" -C "$WORK/src"

# the extmod modules mpconfigport.h turns on, and the app's own modules:
# their names have to be in the qstr table, so they are scanned here too
EXTMOD="extmod/modrandom.c extmod/modjson.c extmod/modre.c extmod/modheapq.c extmod/modtime.c
        extmod/modbinascii.c extmod/modhashlib.c extmod/moddeflate.c
        extmod/vfs.c extmod/modos.c extmod/vfs_reader.c"
EXTMOD=$(echo $EXTMOD)
OWN=$(ls "$HERE"/main/mod_*.c 2>/dev/null | tr '\n' ' ' || true)

B=$WORK/build
rm -rf "$B"
mkdir -p "$B/patched"
cp "$HERE/main/mpconfigport.h" "$HERE/main/p4py_hal.h" "$HERE/main/p4py_time.h" "$B/"
# VfsPosix's file objects without VfsPosix (mod_card.c is the filesystem):
# on whatever MICROPY_VFS_POSIX says, and without sys.stdin/stdout/stderr
# (the console's are mod_p4.c's), and poll.h where the IDF has it. Patched
# before the scan, for its names.
sed -e 's|^#if MICROPY_VFS_POSIX$|#if 1 // P4OS: the file objects alone (see VENDOR.md)|' \
    -e '/^mp_obj_vfs_posix_file_t mp_sys_std[a-z]*_obj = /d' \
    -e 's|^#include <poll.h>$|#include <sys/poll.h>|' \
    "$SRC/extmod/vfs_posix_file.c" > "$B/patched/vfs_posix_file.c"
grep -q "P4OS: the file objects" "$B/patched/vfs_posix_file.c" || { echo "vfs_posix_file.c: the patch did not apply"; exit 1; }
cat > "$B/Makefile" <<EOF
MICROPYTHON_TOP = $SRC
PACKAGE_DIR = $B/upy
SRC_QSTR = $EXTMOD $B/patched/vfs_posix_file.c $OWN
include \$(MICROPYTHON_TOP)/ports/embed/embed.mk
EOF
echo "generating (qstrs, module list)"
make -C "$B" -s > "$B/make.log" 2>&1 || { tail -30 "$B/make.log"; exit 1; }

U=$B/upy
# extmod's sources, and what they include from lib/: re1.5's .c files are
# #included by modre.c, so they become .inc here (the .so's build compiles
# every .c under main/)
mkdir -p "$U/extmod" "$U/lib/re1.5" "$U/lib/libm_dbl" "$U/lib/uzlib" "$U/lib/crypto-algorithms" "$U/shared/timeutils"
for f in $EXTMOD; do cp "$SRC/$f" "$U/extmod/"; done
cp "$B/patched/vfs_posix_file.c" "$U/extmod/"
cp "$SRC"/extmod/modtime.h "$SRC"/extmod/vfs.h "$SRC"/extmod/vfs_posix.h "$SRC"/extmod/misc.h "$U/extmod/"
cp "$SRC"/shared/timeutils/timeutils.[ch] "$U/shared/timeutils/"
# sources that a module #includes rather than compiles on its own
cp "$SRC"/lib/re1.5/re1.5.h "$U/lib/re1.5/"
for f in compilecode recursiveloop charclass dumpcode; do cp "$SRC/lib/re1.5/$f.c" "$U/lib/re1.5/$f.inc"; done
cp "$SRC"/lib/uzlib/*.h "$U/lib/uzlib/"
for f in "$SRC"/lib/uzlib/*.c; do b=$(basename "$f" .c); sed 's#"defl_static\.c"#"defl_static.inc"#' "$f" > "$U/lib/uzlib/$b.inc"; done
cp "$SRC"/lib/crypto-algorithms/sha256.h "$U/lib/crypto-algorithms/"
cp "$SRC"/lib/crypto-algorithms/sha256.c "$U/lib/crypto-algorithms/sha256.inc"
for f in modre moddeflate modhashlib; do
    sed -i.orig 's#\(lib/[a-z0-9.-]*/[a-z0-9_]*\)\.c"#\1.inc"#' "$U/extmod/$f.c" && rm "$U/extmod/$f.c.orig"
done
! grep -n '#include "lib/.*\.c"' "$U"/extmod/*.c "$U"/lib/uzlib/*.inc || { echo "an #include of a .c is left"; exit 1; }
# double-precision maths: musl's, as MicroPython carries it (the firmware
# lends no double libm, and the toolchain's is not position-independent)
cp "$SRC"/lib/libm_dbl/*.c "$SRC"/lib/libm_dbl/*.h "$SRC"/lib/libm_dbl/README "$U/lib/libm_dbl/"
rm -f "$U/lib/libm_dbl/thumb_vfp_sqrt.c"           # ARM only
# the console is the app's (p4py_rt.c), not printf
rm -f "$U/port/mphalport.c"
cp "$SRC/LICENSE" "$U/LICENSE"
cat > "$U/VENDOR.md" <<EOF
# MicroPython $VER, embedded

Generated by \`apps/python/tools/gen_upy.sh\` from MicroPython $VER
(<$URL>, SHA-256 \`$SHA\`) with \`ports/embed\` and this app's
\`main/mpconfigport.h\`. MIT, see LICENSE; \`lib/libm_dbl\` is musl's
(MIT, see its README); \`lib/uzlib\` is zlib-licensed and
\`lib/crypto-algorithms\` public domain (see their headers).

Changes: the sources a module \`#include\`s instead of compiling
(\`lib/re1.5/*.c\`, \`lib/uzlib/*.c\`, \`lib/crypto-algorithms/sha256.c\`)
renamed \`.inc\`, and the \`#include\`s in \`extmod/modre.c\`,
\`moddeflate.c\`, \`modhashlib.c\` and \`lib/uzlib/lz77.c\` pointed there (the
app's build compiles every \`.c\`); \`extmod/vfs_posix_file.c\` built
whatever \`MICROPY_VFS_POSIX\` says (its file objects serve the app's own
filesystem, \`main/mod_card.c\`), without its \`sys.stdin/stdout/stderr\`
(the app's console has them, \`main/mod_p4.c\`) and with \`<sys/poll.h>\`
(the IDF has no \`<poll.h>\`); \`port/mphalport.c\` left
out (the app has its own console); \`lib/libm_dbl/thumb_vfp_sqrt.c\` left
out (ARM).
Do not edit by hand: run the script.
EOF

# the frozen Python modules (frozen/, see its VENDOR.md): their source as
# MicroPython's frozen string tables, compiled when imported
python3 - "$HERE/frozen" "$U/frozen_content.c" <<'PY'
import os, sys
root, out = sys.argv[1], sys.argv[2]
files = sorted(os.path.relpath(os.path.join(d, f), root).replace(os.sep, "/")
               for d, _, fs in os.walk(root) for f in fs if f.endswith(".py"))
def lit(b):
    s = "".join(chr(c) if 32 <= c < 127 and c not in (34, 92, 63) else "\\%03o" % c for c in b)
    return '"' + s + '"'
with open(out, "w") as o:
    o.write("/* Generated by tools/gen_upy.sh from frozen/: do not edit. */\n")
    o.write("#include <stdint.h>\n\n")
    o.write("const char mp_frozen_names[] = {\n")
    for f in files: o.write('    "%s\\0"\n' % f)
    o.write('    "\\0"\n};\n\n')
    srcs = [open(os.path.join(root, f), "rb").read() for f in files]
    o.write("const uint32_t mp_frozen_str_sizes[] = { %s, 0 };\n\n" % ", ".join(str(len(b)) for b in srcs))
    o.write("const char mp_frozen_str_content[] = {\n")
    for f, b in zip(files, srcs):
        o.write("    /* %s */\n" % f)
        for line in b.splitlines(keepends=True):
            o.write("    " + lit(line) + "\n")
        o.write('    "\\0"\n')
    o.write("};\n\n")
    # no frozen .mpy, but the table must be there: with string modules alone
    # MicroPython 1.29 never takes an entry as a string (py/frozenmod.c
    # counts them only when both kinds are on)
    o.write('#include "py/bc.h"\n\n')
    o.write("const mp_frozen_module_t *const mp_frozen_mpy_content[] = { NULL };\n")
print("frozen: " + ", ".join(files))
PY

rm -rf "$HERE/main/upy"
cp -R "$U" "$HERE/main/upy"
echo "main/upy: $(find "$HERE/main/upy" -name '*.c' | wc -l | tr -d ' ') .c files, $(du -sh "$HERE/main/upy" | cut -f1)"
