#!/usr/bin/env python3
"""Makes ng_drivers.c, the Neo Geo core's list of games, from gngeo_data.zip.

gngeo (and RetroESP32-P4, which carries it) describes every game it knows in
a .drv file inside gngeo_data.zip: the ROM files of the MAME set, the region
each one goes to, where and how big. This turns them into C tables compiled
into the core, together with the two CMC decryption tables (rom/cmc42.xor,
rom/cmc50.xor) the same zip carries. gngeo_data.zip is GPL-2 data of gngeo;
it is not kept in the repository.

    python3 tools/gen_drivers.py path/to/gngeo_data.zip > ng_drivers.c
"""
import struct
import sys
import zipfile


def read_drv(data):
    off = 0
    name = data[off:off + 32].split(b'\0')[0].decode(); off += 32
    parent = data[off:off + 32].split(b'\0')[0].decode(); off += 32
    longname = data[off:off + 128].split(b'\0')[0].decode('latin-1'); off += 128
    year = struct.unpack_from('<I', data, off)[0]; off += 4
    sizes = list(struct.unpack_from('<10I', data, off)); off += 40
    n = struct.unpack_from('<I', data, off)[0]; off += 4
    roms = []
    for _ in range(n):
        fn = data[off:off + 32].split(b'\0')[0].decode(); off += 32
        reg = data[off]; off += 1
        src, dest, size, crc = struct.unpack_from('<4I', data, off); off += 16
        roms.append((fn, reg, src, dest, size, crc))
    return name, parent, longname, year, sizes, roms


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def bytes_table(name, data):
    out = ['const uint8_t %s[] = {' % name]
    for i in range(0, len(data), 16):
        out.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
    out.append('};')
    out.append('const unsigned %s_len = %d;' % (name, len(data)))
    return '\n'.join(out)


def main():
    z = zipfile.ZipFile(sys.argv[1])
    drvs = []
    for n in sorted(z.namelist()):
        if n.startswith('rom/') and n.endswith('.drv'):
            drvs.append(read_drv(z.read(n)))
    drvs.sort(key=lambda d: d[0])

    print('/*')
    print(' * P4OS - Emulador, Neo Geo core: the games it knows (ng_drivers.h).')
    print(' * GENERATED by tools/gen_drivers.py from gngeo_data.zip (gngeo, GPL-2):')
    print(' * do not edit by hand. %d games.' % len(drvs))
    print(' */')
    print('#include <string.h>')
    print('#include "ng_drivers.h"')
    print()
    print('static const ng_drvrom_t s_roms[] = {')
    first = []
    k = 0
    for d in drvs:
        first.append(k)
        for (fn, reg, src, dest, size, crc) in d[5]:
            print('    { %s, %d, 0x%x, 0x%x, 0x%x, 0x%08x },' % (cstr(fn), reg, src, dest, size, crc))
            k += 1
    print('};')
    print()
    print('const ng_driver_t ng_drivers[] = {')
    for d, f in zip(drvs, first):
        name, parent, longname, year, sizes, roms = d
        print('    { %s, %s, %s, %d, %d, { %s }, &s_roms[%d] },' % (
            cstr(name), cstr(parent), cstr(longname.strip()), year, len(roms),
            ', '.join('0x%x' % s for s in sizes), f))
    print('};')
    print('const int ng_n_drivers = %d;' % len(drvs))
    print()
    print(bytes_table('ng_cmc42_xor', z.read('rom/cmc42.xor')))
    print()
    print(bytes_table('ng_cmc50_xor', z.read('rom/cmc50.xor')))
    print()
    print('const ng_driver_t *ng_driver_find(const char *name)')
    print('{')
    print('    int lo = 0, hi = ng_n_drivers - 1;')
    print('    while (lo <= hi) {')
    print('        int mid = (lo + hi) / 2;')
    print('        int c = strcmp(name, ng_drivers[mid].name);')
    print('        if (c == 0) return &ng_drivers[mid];')
    print('        if (c < 0) hi = mid - 1; else lo = mid + 1;')
    print('    }')
    print('    return 0;')
    print('}')


if __name__ == '__main__':
    main()
