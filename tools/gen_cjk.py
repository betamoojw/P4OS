#!/usr/bin/env python3
"""Build the offline SC/TC glyph subset for the existing 12 MiB storage partition.

Requires Pillow and fonttools. Inputs: NotoSansSC.ttf/NotoSansTC.ttf (OFL).
The committed image is sufficient for firmware builds; no network is used.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import zlib
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SIZE = 48

def is_cjk(cp):
    return 0x2e80 <= cp < 0xe000 or 0xff00 <= cp <= 0xffef

def common_characters(code):
    encoding = 'gb2312' if code == 'zh-Hans' else 'big5'
    points = set()
    for lead in range(0x81, 0xff):
        for trail in range(0x40, 0xff):
            try:
                text = bytes((lead, trail)).decode(encoding)
            except UnicodeDecodeError:
                continue
            if len(text) == 1 and is_cjk(ord(text)):
                points.add(ord(text))
    return points

def regular_font(path):
    font = ImageFont.truetype(str(path), SIZE)
    axes = TTFont(path)['fvar'].axes
    font.set_variation_by_axes([400 if a.axisTag == 'wght' else a.defaultValue for a in axes])
    return font

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--fonts', type=Path, default=ROOT / 'build/chinese-fonts')
    args = ap.parse_args()
    payload = bytearray()
    manifest = {'format': 1, 'size': SIZE, 'fonts': {}, 'glyphs': {}, 'render': {'weight': 400, 'bpp': 2, 'offset_y': -14}}
    for variant, (code, family) in enumerate([('zh-Hans', 'SC'), ('zh-Hant', 'TC')]):
        path = args.fonts / f'NotoSans{family}.ttf'
        font = regular_font(path)
        cmap = TTFont(path).getBestCmap()
        backup_path = args.fonts / 'NotoSansSC.ttf'
        backup = regular_font(backup_path)
        backup_cmap = TTFont(backup_path).getBestCmap()
        # Include names of both languages, even while another language is selected.
        text = '简体中文繁體中文'
        for p in (ROOT / 'lang' / code).glob('*.lang'):
            text += ''.join(line.split('\t', 1)[1] for line in p.read_text(encoding='utf-8').splitlines() if '\t' in line)
        points = sorted(common_characters(code) | {ord(c) for c in text if is_cjk(ord(c))})
        missing = [hex(cp) for cp in points if cp not in cmap and cp not in backup_cmap]
        if missing:
            raise ValueError(f'{code}: missing glyphs {missing}')
        for cp in points:
            image = Image.new('L', (SIZE, SIZE))
            face = font if cp in cmap else backup
            bounds = face.getbbox(chr(cp))

            # Align the ideographic em square; punctuation keeps its font placement.
            if bounds[1] >= 14 and bounds[3] <= 62 and bounds[0] >= 0 and bounds[2] <= SIZE:
                ImageDraw.Draw(image).text((0, -14), chr(cp), font=face, fill=255)
            else:
                # A few rare ideographs exceed the em square: retain all strokes.
                glyph = Image.new('L', (bounds[2]-bounds[0], bounds[3]-bounds[1]))
                ImageDraw.Draw(glyph).text((-bounds[0], -bounds[1]), chr(cp), font=face, fill=255)
                glyph.thumbnail((SIZE, SIZE), Image.Resampling.LANCZOS)
                image.paste(glyph, ((SIZE-glyph.width)//2, (SIZE-glyph.height)//2))
            pixels = list(image.get_flattened_data())
            payload += struct.pack('<I', (variant << 24) | cp)
            payload += bytes(sum(((pixels[i+j] * 3 + 127) // 255) << (6-2*j) for j in range(4)) for i in range(0, len(pixels), 4))
        manifest['fonts'][family] = hashlib.sha256(path.read_bytes()).hexdigest()
        manifest['glyphs'][code] = points
    count = len(payload) // (4 + SIZE * SIZE // 4)
    header = struct.pack('<8s6I', b'P4CJK001', 1, SIZE, count, len(payload), zlib.crc32(payload), 0)
    image = header + payload
    assert len(image) <= 12 * 1024 * 1024
    out = ROOT / 'assets' / 'cjk'
    out.mkdir(parents=True, exist_ok=True)
    (out / 'cjk.bin').write_bytes(image)
    manifest['sha256'] = hashlib.sha256(image).hexdigest()
    (out / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    (ROOT / 'components/aos_fonts/include/aos_cjk_resource.h').write_text(
        '/* Generated by tools/gen_cjk.py. */\n#pragma once\n#define AOS_CJK_RESOURCE_CRC 0x%08xu\n' % zlib.crc32(payload), encoding='utf-8')
    (out / 'OFL.txt').write_bytes((args.fonts / 'OFL.txt').read_bytes())
    print(f'{count} regional glyphs, {len(image)} bytes -> {out}')

if __name__ == '__main__':
    main()

