#!/usr/bin/env python3
"""
P4OS - Emulador, Mega Drive core: the YM2612's two computed tables.

ym2612.c built its power table and its logarithmic sine table at start-up
with pow(), floor(), sin() and log() in double precision. The firmware does
not lend double-precision libm to the apps (only the float functions), and
the float versions round two of the 1280 entries differently, so the values
are worked out here, with the same formulas in double precision, and
ym2612.c copies them in (init_tables).

    python3 gen_ym2612_tables.py <output dir>
"""
import math
import os
import sys

TL_RES_LEN = 256
SIN_LEN = 1024
ENV_STEP = 128.0 / 1024.0


def power_table():
    out = []
    for x in range(TL_RES_LEN):
        m = (1 << 16) / math.pow(2, (x + 1) * (ENV_STEP / 4.0) / 8.0)
        m = math.floor(m)
        n = int(m)
        n >>= 4
        n = (n >> 1) + 1 if n & 1 else n >> 1
        n <<= 2
        out.append(n)
    return out


def sine_table():
    out = []
    for i in range(SIN_LEN):
        m = math.sin(((i * 2) + 1) * math.pi / SIN_LEN)
        if m > 0.0:
            o = 8 * math.log(1.0 / m) / math.log(2)
        else:
            o = 8 * math.log(-1.0 / m) / math.log(2)
        o = o / (ENV_STEP / 4)
        n = int(2.0 * o)
        n = (n >> 1) + 1 if n & 1 else n >> 1
        out.append(n * 2 + (0 if m >= 0.0 else 1))
    return out


def emit(f, name, vals):
    f.write("static const unsigned short %s[%d] = {\n" % (name, len(vals)))
    for k in range(0, len(vals), 16):
        f.write("  " + ",".join("%d" % v for v in vals[k:k + 16]) + ",\n")
    f.write("};\n")


def main():
    out = os.path.join(sys.argv[1], "ym2612_tables.h")
    with open(out, "w") as f:
        f.write("/* Generated by cores/md/tools/gen_ym2612_tables.py: do not edit.\n"
                " * The YM2612's power table (tl_tab's first column, 13 bits) and its\n"
                " * logarithmic sine table, as ym2612.c's init_tables() computed them. */\n")
        emit(f, "ym_tl_base", power_table())
        emit(f, "ym_sin_base", sine_table())
    print("written", out)


if __name__ == "__main__":
    main()
