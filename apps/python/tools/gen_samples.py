#!/usr/bin/env python3
"""
Writes main/py_samples.c: the sample apps in scripts/ as strings, which the
app writes to the card's /python/apps the first time it finds no such
folder (py_script.c, apps_scan). Run it after changing a sample:

    python3 apps/python/tools/gen_samples.py

The output is committed: the CI needs nothing.
"""
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, "scripts")
OUT = os.path.join(HERE, "main", "py_samples.c")


def lit(b):
    s = "".join(chr(c) if 32 <= c < 127 and c not in (34, 92, 63) else "\\%03o" % c for c in b)
    return '"' + s + '"'


files = sorted(f for f in os.listdir(SRC) if f.endswith((".py", ".aic")) and not f.startswith("."))
with open(OUT, "w") as o:
    o.write("/* Generated by tools/gen_samples.py from scripts/: do not edit. */\n")
    o.write('#include "py_samples.h"\n\n')
    o.write("const py_sample_t py_samples[] = {\n")
    for f in files:
        b = open(os.path.join(SRC, f), "rb").read()
        o.write("    { %s, %d,\n" % (lit(f.encode()), len(b)))
        for line in b.splitlines(keepends=True):
            o.write("      " + lit(line) + "\n")
        o.write("    },\n")
    o.write("    { 0, 0, 0 },\n};\n")
print("main/py_samples.c: " + ", ".join(files), file=sys.stderr)
